import {
  Tooltip,
  TooltipContent,
  TooltipTrigger,
} from "@/components/ui/tooltip";
import { ExternalLink } from "lucide-react";
import { useWorkspaceConfig } from "@/lib/workspace-config";

const ENDPOINT_NAME = "energy-theft-gemini-gateway";
const MODEL_ID = "Gemini 2.0 Flash";
const PROVIDER = "Google Gemini";

const GOOGLE_BLUE = "#4285F4";

function GeminiLogo({ className }: { className?: string }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      className={className}
      xmlns="http://www.w3.org/2000/svg"
    >
      <path
        d="M12 2C12 2 14.5 7.5 17 10C19.5 12.5 22 12 22 12C22 12 19.5 12.5 17 15C14.5 17.5 12 22 12 22C12 22 9.5 17.5 7 15C4.5 12.5 2 12 2 12C2 12 4.5 12.5 7 10C9.5 7.5 12 2 12 2Z"
        fill={GOOGLE_BLUE}
        opacity="0.15"
        stroke={GOOGLE_BLUE}
        strokeWidth="1.5"
        strokeLinejoin="round"
      />
      <circle cx="12" cy="12" r="2.5" fill={GOOGLE_BLUE} />
    </svg>
  );
}

interface GeminiBadgeProps {
  size?: "sm" | "md";
  showModel?: boolean;
  className?: string;
}

export function GeminiBadge({
  size = "sm",
  showModel = false,
  className = "",
}: GeminiBadgeProps) {
  const { data: wsConfig } = useWorkspaceConfig();
  const endpointUrl = wsConfig
    ? `${wsConfig.workspace_url}/#mlflow/endpoints/${ENDPOINT_NAME}`
    : "#";
  const iconSize = size === "sm" ? "h-3.5 w-3.5" : "h-4 w-4";
  const textSize = size === "sm" ? "text-xs" : "text-sm";
  const linkSize = size === "sm" ? "h-2.5 w-2.5" : "h-3 w-3";

  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <a
          href={endpointUrl}
          target="_blank"
          rel="noopener noreferrer"
          className={`inline-flex items-center gap-1.5 rounded-md border px-2 py-0.5 transition-colors ${textSize} ${className}`}
          style={{
            borderColor: `${GOOGLE_BLUE}40`,
            backgroundColor: `${GOOGLE_BLUE}08`,
          }}
          onClick={(e) => e.stopPropagation()}
        >
          <GeminiLogo className={iconSize} />
          <span
            className="font-medium"
            style={{ color: GOOGLE_BLUE }}
          >
            {showModel ? MODEL_ID : PROVIDER}
          </span>
          <ExternalLink
            className={`${linkSize} opacity-40`}
            style={{ color: GOOGLE_BLUE }}
          />
        </a>
      </TooltipTrigger>
      <TooltipContent
        side="bottom"
        className="max-w-[320px] text-xs space-y-2 bg-gray-900 text-white border-gray-700"
      >
        <div className="flex items-center gap-2">
          <GeminiLogo className="h-5 w-5" />
          <div>
            <p className="font-semibold" style={{ color: GOOGLE_BLUE }}>
              {PROVIDER} — {MODEL_ID}
            </p>
            <p className="text-gray-300">
              via Databricks AI Gateway
            </p>
          </div>
        </div>
        <p className="text-gray-300 leading-relaxed">
          Market intelligence is generated by Google Gemini routed through a
          separate AI Gateway endpoint{" "}
          <code className="text-[10px] bg-gray-700 text-gray-200 px-1 py-0.5 rounded">
            {ENDPOINT_NAME}
          </code>
          . Same governance: PII guardrails, rate limits, and inference table
          logging — different cloud provider.
        </p>
        <a
          href={endpointUrl}
          target="_blank"
          rel="noopener noreferrer"
          className="text-[10px] font-medium block hover:underline"
          style={{ color: GOOGLE_BLUE }}
          onClick={(e) => e.stopPropagation()}
        >
          Click to view the Model Serving endpoint →
        </a>
      </TooltipContent>
    </Tooltip>
  );
}

export { GeminiLogo, GOOGLE_BLUE, MODEL_ID as GEMINI_MODEL_ID, PROVIDER as GEMINI_PROVIDER, ENDPOINT_NAME as GEMINI_ENDPOINT_NAME };
